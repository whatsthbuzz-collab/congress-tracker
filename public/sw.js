// Service worker for the installable app.
// Network first: visitors always get the latest data when online. The cache
// is only a fallback so previously viewed pages still open offline. Requests
// to other sites (fonts, photos, Census, OpenStreetMap) are never cached.
const CACHE = 'congress-tracker-v1';

self.addEventListener('install', () => self.skipWaiting());

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  event.respondWith(
    fetch(req)
      .then((res) => {
        if (res.ok) {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(req, copy));
        }
        return res;
      })
      .catch(() =>
        caches.match(req).then((hit) =>
          hit || (req.mode === 'navigate' ? caches.match(self.registration.scope) : undefined)
        ).then((hit) => hit || Response.error())
      )
  );
});
